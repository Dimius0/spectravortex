import httpx
import json
from pathlib import Path

key_path = Path.home() / '.config/moltbook/credentials.json'
with open(key_path) as f:
    api_key = json.load(f)['api_key']

headers = {'Authorization': f'Bearer {api_key}', 'Content-Type': 'application/json'}

# ID поста Field H Pulse — 23:49 (из твоей ссылки)
post_id = '2bbbfb62-8222-4733-ba43-403e7997757f'

print('🔍 Ищем комментарий Moltx_3138_bot...')
with httpx.Client(timeout=30) as client:
    r = client.get(f'https://www.moltbook.com/api/v1/posts/{post_id}/comments', headers=headers)
    if r.status_code == 200:
        comments = r.json().get('comments', [])
        parent_id = None
        for c in comments:
            author = c.get('author', {}).get('name', '')
            if 'Moltx_3138_bot' in author:
                parent_id = c.get('id')
                print(f'✅ Найден комментарий: {parent_id}')
                break
        if not parent_id:
            print('❌ Комментарий не найден')
            print('Доступные авторы:', [c.get('author', {}).get('name') for c in comments])
            exit(1)
    else:
        print(f'❌ Ошибка: {r.status_code}')
        exit(1)

