# ============================================================

def plot_group(group_data, group_name, filename, ylabel='Время жизни / распространённость'):
    plt.figure(figsize=(12, 6))
    
    colors = plt.cm.tab10(np.linspace(0, 1, len(group_data)))
    
    for i, (element, values) in enumerate(group_data.items()):
        N_vals = np.array(sorted(values.keys()))
        E_vals = np.array([values[n] for n in N_vals])
        
        plt.plot(N_vals, E_vals, 'o-', color=colors[i], linewidth=2, 
                markersize=8, label=element, alpha=0.8)
    
    plt.xlabel('Число нейтронов (N)', fontsize=12)
    plt.ylabel(ylabel, fontsize=12)
    plt.title(f'Группа {group_name}', fontsize=14)
    plt.grid(True, alpha=0.3)
    plt.legend()
    plt.tight_layout()
    plt.savefig(filename, dpi=150)
    print(f"✅ {filename} сохранён")

# Строим
